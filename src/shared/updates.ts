/**
 * Состояние обновления — одно на всё приложение.
 *
 * Обновления приходят с GitHub: там лежат собранные установщики, и рядом с
 * ними — описание последней версии, по которому приложение и понимает, что
 * вышло что-то новее. Скачивается всё само и в стороне от прослушивания;
 * установка происходит при выходе, чтобы ничего не обрывалось на полуслове.
 */
export type UpdatePhase =
  /** Ещё не смотрели. */
  | 'idle'
  | 'checking'
  /** Установлено самое новое. */
  | 'current'
  /** Новая версия есть и качается. */
  | 'downloading'
  /** Скачано и встанет при следующем выходе — или прямо сейчас по кнопке. */
  | 'ready'
  | 'error'
  /** Запуск из исходников: обновлять нечего. */
  | 'unsupported'

export interface UpdateState {
  phase: UpdatePhase
  /** Версия, которая качается или ждёт установки. */
  version: string | null
  /** Сколько скачано, от нуля до единицы. */
  progress: number
  /** Что пошло не так — человеческими словами. */
  error: string | null
  /** Когда в последний раз удалось посмотреть. */
  checkedAt: number | null
}

export const IDLE_UPDATE: UpdateState = {
  phase: 'idle',
  version: null,
  progress: 0,
  error: null,
  checkedAt: null
}
