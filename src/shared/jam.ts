import type { ServiceId } from './domain'

/**
 * Общая сессия: участники добавляют треки и переключают.
 *
 * Играет всё равно только у ведущего — он один, у кого есть звук и очередь.
 * Поэтому участники не меняют состояние, а просят, и здесь описано, о чём
 * можно попросить. Всё остальное, что они видят, приходит обычным потоком
 * совместного прослушивания.
 */

/**
 * Трек в описании, а не в номерах.
 *
 * Номера у сервисов свои, и добавленный из VK трек нечем открыть тому, у кого
 * только Яндекс. Поэтому едет описание, а ведущий ищет по нему у себя — тем
 * же поиском, которым один сервис выручает другой.
 */
export interface JamSeed {
  title: string
  artists: string[]
  durationMs: number
  /** Откуда трек у того, кто его предложил, — подсказка для поиска. */
  service: ServiceId
  nativeId: string
}

export type JamMessage =
  | { type: 'add'; track: JamSeed; from?: string }
  | { type: 'next'; from?: string }
  | { type: 'prev'; from?: string }
  /**
   * Переставить трек в общей очереди.
   *
   * Трек называется идентификатором ведущего — участник видит именно его в
   * присланной очереди, — а место отсчитывается от играющего: `to: 0` значит
   * «следующим». Не номер в очереди ведущего: пока просьба шла, там могло
   * что-то сдвинуться, а «через два трека» остаётся верным и тогда.
   */
  | { type: 'move'; id: string; to: number; from?: string }
  | { type: 'remove'; id: string; from?: string }

/**
 * Что ведущий разрешил участникам. Добавлять можно всегда — ради этого сессию
 * и открывают; остальное решает ведущий.
 */
export interface JamPerms {
  /** «Дальше» и «назад» из плиты участника. */
  skip: boolean
  /** Переставлять и убирать треки общей очереди. */
  edit: boolean
}

export const DEFAULT_JAM_PERMS: JamPerms = { skip: true, edit: true }

/** Кто что сделал в общей сессии — короткая лента для окна. */
export interface JamEvent {
  at: number
  text: string
}

/**
 * Трек в общей очереди — так, как его видит участник.
 *
 * Полный `Track` сюда не годится: у ведущего он свой, со ссылками и номерами
 * его сервиса, и участнику из этого нужно только «что играет дальше и кто это
 * предложил». Заодно тело состояния остаётся маленьким — ретранслятор держит
 * восемь килобайт на сессию.
 */
export interface JamQueueItem {
  id: string
  title: string
  artists: string[]
  coverUrl: string | null
  /** Кто предложил. Пусто — трек поставил сам ведущий. */
  by?: string
}

/** Сколько ближайших треков показывать участникам. */
export const JAM_QUEUE_LIMIT = 12
