import type { ServiceId } from './domain'

/**
 * Общая сессия: участники добавляют треки и переключают.
 *
 * Играет всё равно только у ведущего — он один, у кого есть звук и очередь.
 * Поэтому участники не меняют состояние, а просят, и здесь описано, о чём
 * можно попросить. Всё остальное, что они видят, приходит обычным потоком
 * совместного прослушивания.
 */

/**
 * Трек в описании, а не в номерах.
 *
 * Номера у сервисов свои, и добавленный из VK трек нечем открыть тому, у кого
 * только Яндекс. Поэтому едет описание, а ведущий ищет по нему у себя — тем
 * же поиском, которым один сервис выручает другой.
 */
export interface JamSeed {
  title: string
  artists: string[]
  durationMs: number
  /** Откуда трек у того, кто его предложил, — подсказка для поиска. */
  service: ServiceId
  nativeId: string
}

export type JamMessage =
  | { type: 'add'; track: JamSeed; from?: string }
  | { type: 'next'; from?: string }
  | { type: 'prev'; from?: string }

/** Кто что сделал в общей сессии — короткая лента для окна. */
export interface JamEvent {
  at: number
  text: string
}
