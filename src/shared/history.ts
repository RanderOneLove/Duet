import type { ServiceId } from './domain'

/**
 * Откуда заиграл трек — для итогов: сколько дала волна, сколько свои списки,
 * сколько общая сессия.
 */
export type PlaySource = 'queue' | 'wave' | 'trackWave' | 'jamHost' | 'jamGuest' | 'follow'

/**
 * Одно прослушивание в журнале.
 *
 * Поля короткие: журнал — строка на трек, за год их десятки тысяч, и файл
 * должен оставаться мегабайтами, а не десятками. Всё нужное для итогов лежит
 * здесь же, без похода к сервисам: к декабрю трек могут убрать из каталога,
 * а прослушивание от этого не перестаёт быть.
 */
export interface PlayRecord {
  /** Когда зазвучал, мс от эпохи. */
  t: number
  /** Идентификатор трека, `service:nativeId`. */
  id: string
  s: ServiceId
  /** Название. */
  n: string
  /** Исполнители. */
  a: string[]
  /** Альбом. */
  al: string | null
  /** Обложка. */
  c: string | null
  /** Длительность трека, мс. */
  d: number
  /** Сколько на самом деле звучало, мс, — без пауз и перемоток. */
  l: number
  src: PlaySource
  /** Дослушан почти до конца. */
  f?: 1
  /** Спасён: просили трек этого сервиса, а сыграл найденный во втором. */
  r?: ServiceId
  /** Пока играл, был открыт текст. */
  ly?: 1
  /** Был в «Нравится». */
  lk?: 1
  /** С кем слушали — имена из комнаты Jam. */
  w?: string[]
}

/** Сводка для настроек: есть ли журнал и с какого времени. */
export interface HistoryInfo {
  plays: number
  /** Самое раннее прослушивание, мс от эпохи, или null для пустого журнала. */
  since: number | null
}
